/** Enhancements are opt-in per locale and route; never reuse another route's copy. */
export function getRouteEnhancement(lang: Lang, pagePath: string): RouteEnhancement | undefined {
  if (lang !== "ru") return undefined;
  if (pagePath === "/route/belarus/poland") return belarusPolandRu;

  if (!Object.hasOwn(routeSpecificRu, pagePath)) return undefined;
  const content = routeSpecificRu[pagePath];

  return {
    ...belarusPolandRu,
    quickFacts: [
      { label: "Для каких номеров", value: content.registration },
      ...belarusPolandRu.quickFacts.slice(1),
    ],
    border: content.border,
    scenarios: content.scenarios,
  };
}
